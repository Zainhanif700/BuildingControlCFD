"""
Window settings for the new setup: only W1, W3 and W6 can open (closed or 0.2-2.0 m/s each), door 1 open, door 2 closed.
28 settings, 8 of them held out for testing; writes scenarios_v2.txt.
Usage: python3 scenarios_v2.py
"""
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
OPENABLE = (0, 2, 5)             # W1, W3, W6 (index in V1..V8)
DOORS = "1,0"                    # door 1 open, door 2 closed
V_LO, V_HI, P_CLOSED = 0.2, 2.0, 0.3
N_RANDOM, N_TEST, SEED = 16, 8, 0


def to_V(w):
    V = [0.0] * 8
    for k, v in zip(OPENABLE, w):
        V[k] = float(v)
    return V


def build():
    rows = []
    for s in (0.5, 1.0, 2.0):            # one window open
        for i in range(3):
            w = [0.0, 0.0, 0.0]
            w[i] = s
            rows.append(("train", tuple(w)))
    for s in (0.5, 1.0, 2.0):            # all three open
        rows.append(("train", (s, s, s)))
    rng = np.random.default_rng(SEED)
    seen = {r[1] for r in rows}
    rand = []
    while len(rand) < N_RANDOM:
        w = tuple(0.0 if rng.random() < P_CLOSED else round(round(float(rng.uniform(V_LO, V_HI)) / 0.05) * 0.05, 2)
                  for _ in range(3))
        if max(w) == 0 or w in seen:
            continue
        seen.add(w)
        rand.append(w)
    test = set(rng.choice(N_RANDOM, N_TEST, replace=False).tolist())
    rows += [("test" if i in test else "train", w) for i, w in enumerate(rand)]
    return [(f"N{i + 1:02d}", split, w) for i, (split, w) in enumerate(rows)]


def main():
    rows = build()
    path = os.path.join(HERE, "scenarios_v2.txt")
    with open(path, "w") as f:
        f.write("# name split V1..V8 doors(door1,door2) speeds(W1,W3,W6) -- generated by scenarios_v2.py\n")
        for name, split, w in rows:
            f.write(f"{name} {split} {','.join(f'{v:g}' for v in to_V(w))} {DOORS} {' '.join(f'{v:g}' for v in w)}\n")
    n_test = sum(r[1] == "test" for r in rows)
    print(f"wrote {path}: {len(rows)} settings ({len(rows) - n_test} train, {n_test} test)")
    for name, split, w in rows:
        print(f"  {name} {split:5s} W1 {w[0]:4g}  W3 {w[1]:4g}  W6 {w[2]:4g} m/s")


if __name__ == "__main__":
    main()
