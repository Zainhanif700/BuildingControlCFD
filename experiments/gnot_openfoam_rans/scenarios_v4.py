"""
Window and door settings with all openings: every window is closed, an inlet (0.2-2.0 m/s) or an outlet (written as -1),
and each door is open or closed. Keeps the 28 settings of scenarios_v2.txt (W1, W3, W6, door 1 open) and adds 40 new
ones, 10 for each door combination (both open, only door 1, only door 2, both closed); 2 of each 10 are test settings.
Every setting has at least one inlet window and at least one way out (open door or outlet window).
Writes scenarios_v4.txt.
Usage: python3 scenarios_v4.py
"""
import os

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
V_LO, V_HI = 0.2, 2.0
P_CLOSED, P_INLET = 0.45, 0.35          # the rest (0.20) is an outlet window
N_PER_DOORS, N_TEST_PER_DOORS, SEED = 10, 2, 1
DOOR_GROUPS = [(1, 1), (1, 0), (0, 1), (0, 0)]


def old_rows():
    rows = []
    for line in open(os.path.join(HERE, "scenarios_v2.txt")):
        p = line.split()
        if p and not p[0].startswith("#"):
            rows.append((p[0], p[1], [float(v) for v in p[2].split(",")], tuple(int(d) for d in p[3].split(","))))
    return rows


def one_window(rng):
    r = rng.random()
    if r < P_CLOSED:
        return 0.0
    if r < P_CLOSED + P_INLET:
        return round(round(float(rng.uniform(V_LO, V_HI)) / 0.05) * 0.05, 2)
    return -1.0


def build():
    rows = old_rows()
    rng = np.random.default_rng(SEED)
    seen = {(tuple(V), d) for _, _, V, d in rows}
    k = 0
    for doors in DOOR_GROUPS:
        group = []
        while len(group) < N_PER_DOORS:
            V = [one_window(rng) for _ in range(8)]
            if not any(v > 0 for v in V):
                continue
            if not any(doors) and not any(v < 0 for v in V):
                continue
            if (tuple(V), doors) in seen:
                continue
            seen.add((tuple(V), doors))
            group.append(V)
        test = set(rng.choice(N_PER_DOORS, N_TEST_PER_DOORS, replace=False).tolist())
        for i, V in enumerate(group):
            k += 1
            rows.append((f"A{k:02d}", "test" if i in test else "train", V, doors))
    return rows


def main():
    rows = build()
    path = os.path.join(HERE, "scenarios_v4.txt")
    with open(path, "w") as f:
        f.write("# name split V1..V8 (>0 inlet m/s, 0 closed, -1 outlet window) doors(door1,door2) -- generated by scenarios_v4.py\n")
        for name, split, V, d in rows:
            f.write(f"{name} {split} {','.join(f'{v:g}' for v in V)} {d[0]},{d[1]}\n")
    n_test = sum(r[1] == "test" for r in rows)
    print(f"wrote {path}: {len(rows)} settings ({len(rows) - n_test} train, {n_test} test)")
    new = [r for r in rows if r[0].startswith("A")]
    win = np.array([r[2] for r in new])
    print(f"  new settings: {len(new)}; per window: inlet {(win > 0).sum(0).tolist()}, outlet {(win < 0).sum(0).tolist()}, "
          f"closed {(win == 0).sum(0).tolist()}")
    for name, split, V, d in new:
        desc = " ".join(f"W{i + 1}:{'in ' + format(v, 'g') if v > 0 else ('out' if v < 0 else '-')}" for i, v in enumerate(V))
        print(f"  {name} {split:5s} doors {d[0]},{d[1]}  {desc}")


if __name__ == "__main__":
    main()
