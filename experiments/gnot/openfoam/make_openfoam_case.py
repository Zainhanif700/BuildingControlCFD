"""
LEVEL 1 reference: generate an OpenFOAM (v2412, openfoam.com) case of the classroom for one
window setting -- the SAME equations and boundary conditions as the physics-informed model:

  incompressible laminar Navier-Stokes, nu = 0.01 m^2/s (train_gnot.NU), rho = 1 (kinematic p)
  open windows  : uniform inflow v = -V_k tanh(3 t / TAU_RAMP)  (tabulated time series)
  closed windows, walls, floor, ceiling, columns : no-slip
  doors         : p = 0, velocity pressureInletOutletVelocity (free, backflow allowed)
  window speed scaled so each window delivers exactly V_k * A_k on the grid (flux matching)
  initial state : at rest
CO2 is NOT solved in OpenFOAM (no compiler in the conda build for a coded Gaussian source);
compare_with_openfoam.py transports CO2 through the OpenFOAM flow with the verified
finite-volume solver of check_co2_with_model_flow.py (same source, D and BCs as the model).

Mesh: uniform hexahedra with EXACTLY the cell layout of check_co2_with_model_flow.Grid
(n = round(L/dx) per axis), columns removed as staircase cells (topoSet cylinderToCell +
subsetMesh), window/door patches = boundary faces whose centre lies in the opening.

Usage:
  python3 make_openfoam_case.py --scenario "W1 1m/s" [--dx 0.1] [--out cases]
Scenario names are those of check_physics_consistency.scenarios() (e.g. "W1 1m/s",
"all 1m/s", "W1+W8 2m/s"), or --V 1,0,0,0,0,0,0,0 with --name.
"""
import argparse
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
try:  # the room geometry lives in point_sampler.py, which imports torch/numpy
    from point_sampler import ROOM_X, ROOM_Y, ROOM_Z, WINDOWS, DOORS, COLUMNS, TAU_RAMP, T_MAX  # noqa: E402
except ImportError as exc:
    raise SystemExit(f"{exc}: run this generator in the training environment (conda activate cfd); "
                     f"only the OpenFOAM run itself needs the 'foam' environment.")

NU = 0.01          # must equal train_gnot.NU (checked at the end of main())
HEADER = """/*--------------------------------*- C++ -*----------------------------------*\\
  Generated by make_openfoam_case.py for the GNOT thesis (level-1 reference)
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    object      {obj};
}}
"""


def write(path, cls, obj, body):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(HEADER.format(cls=cls, obj=obj) + body)


def scenario_V(name):
    """Same scenario definitions as check_physics_consistency.scenarios() (no torch import)."""
    z = [0.0] * len(WINDOWS)

    def only(**kw):
        V = list(z)
        for k, v in kw.items():
            V[int(k[1:]) - 1] = float(v)
        return V
    table = {
        "W1 1m/s": only(W1=1), "W1 3m/s": only(W1=3), "W4 3m/s": only(W4=3), "W8 3m/s": only(W8=3),
        "W1+W8 2m/s": only(W1=2, W8=2), "W4+W5 2m/s": only(W4=2, W5=2),
        "all 1m/s": [1.0] * len(WINDOWS), "all 3m/s": [3.0] * len(WINDOWS),
        "W1 0.2m/s": only(W1=0.2), "all 0.2m/s": [0.2] * len(WINDOWS),
    }
    if name not in table:
        raise SystemExit(f"unknown scenario {name!r}; known: {list(table)} (or use --V ... --name ...)")
    return table[name]


def ramp_table(V, t_end):
    """Tabulated (t, (0 -V tanh(3t/TAU) 0)) -- dense during the ramp, then constant."""
    ts = [i * 0.05 for i in range(0, 101)] + [6.0, 10.0, t_end + 1.0]
    rows = []
    for t in ts:
        rows.append(f"            ({t:.4f} (0 {-V * math.tanh(3.0 * t / TAU_RAMP):.8f} 0))")
    return "\n".join(rows)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--scenario", default=None)
    ap.add_argument("--V", default=None, help="comma-separated V1..V8 (with --name)")
    ap.add_argument("--name", default=None)
    ap.add_argument("--dx", type=float, default=0.1)
    ap.add_argument("--t-end", type=float, default=T_MAX)
    ap.add_argument("--write-interval", type=float, default=2.0, help="s between saved fields")
    ap.add_argument("--procs", type=int, default=4)
    ap.add_argument("--out", default=os.path.join(HERE, "cases"))
    args = ap.parse_args()
    if args.V:
        V = [float(v) for v in args.V.split(",")]
        name = args.name or "custom"
    else:
        V = scenario_V(args.scenario or "W1 1m/s")
        name = (args.scenario or "W1 1m/s")
    assert len(V) == len(WINDOWS)
    tag = name.replace(" ", "_").replace("/", "").replace("+", "p").replace(".", "p")
    case = os.path.join(args.out, f"{tag}_dx{args.dx:g}")

    L = [ROOM_X[1] - ROOM_X[0], ROOM_Y[1] - ROOM_Y[0], ROOM_Z[1] - ROOM_Z[0]]
    n = [max(4, round(l / args.dx)) for l in L]      # identical to check_co2_with_model_flow.Grid
    h = [l / m for l, m in zip(L, n)]
    x0, y0, z0 = ROOM_X[0], ROOM_Y[0], ROOM_Z[0]
    x1, y1, z1 = ROOM_X[1], ROOM_Y[1], ROOM_Z[1]

    # ---------------- system/blockMeshDict
    write(os.path.join(case, "system/blockMeshDict"), "dictionary", "blockMeshDict", f"""
scale 1;
vertices
(
    ({x0} {y0} {z0}) ({x1} {y0} {z0}) ({x1} {y1} {z0}) ({x0} {y1} {z0})
    ({x0} {y0} {z1}) ({x1} {y0} {z1}) ({x1} {y1} {z1}) ({x0} {y1} {z1})
);
blocks ( hex (0 1 2 3 4 5 6 7) ({n[0]} {n[1]} {n[2]}) simpleGrading (1 1 1) );
boundary
(
    walls
    {{
        type wall;
        faces ( (0 4 7 3) (1 2 6 5) (0 1 5 4) (3 7 6 2) (0 3 2 1) (4 5 6 7) );
    }}
    columns {{ type wall; faces (); }}
);
""")
    # ---------------- system/topoSetDict (1): fluid cells = box minus columns
    col_actions = "\n".join(
        f"""    {{ name fluid; type cellSet; action subtract; source cylinderToCell;
      p1 ({cx} {cy} {z0 - 1}); p2 ({cx} {cy} {z1 + 1}); radius {r}; }}"""
        for cx, cy, r, _, _ in COLUMNS)
    write(os.path.join(case, "system/topoSetDict.fluid"), "dictionary", "topoSetDict", f"""
actions
(
    {{ name fluid; type cellSet; action new; source boxToCell;
      box ({x0 - 1} {y0 - 1} {z0 - 1}) ({x1 + 1} {y1 + 1} {z1 + 1}); }}
{col_actions}
);
""")
    # ---------------- system/topoSetDict (2): opening face sets (face centre inside the opening)
    e = 0.25 * min(h)
    acts = []
    for k, (a, b, c, d) in enumerate(WINDOWS):
        acts.append(f"""    {{ name window{k + 1}; type faceSet; action new; source boxToFace;
      box ({a} {y1 - e} {c - e}) ({b} {y1 + e} {d + e}); }}""")
    for j, (a, b, c, d) in enumerate(DOORS):
        acts.append(f"""    {{ name door{j + 1}; type faceSet; action new; source boxToFace;
      box ({a} {y0 - e} {c - e}) ({b} {y0 + e} {d}); }}""")
    write(os.path.join(case, "system/topoSetDict.openings"), "dictionary", "topoSetDict",
          "\nactions\n(\n" + "\n".join(acts) + "\n);\n")
    # ---------------- system/createPatchDict
    pats = [f"    {{ name window{k + 1}; patchInfo {{ type patch; }} constructFrom set; set window{k + 1}; }}"
            for k in range(len(WINDOWS))]
    pats += [f"    {{ name door{j + 1}; patchInfo {{ type patch; }} constructFrom set; set door{j + 1}; }}"
             for j in range(len(DOORS))]
    write(os.path.join(case, "system/createPatchDict"), "dictionary", "createPatchDict",
          "\npointSync false;\npatches\n(\n" + "\n".join(pats) + "\n);\n")

    # ---------------- 0/U and 0/p
    # flux matching: on the grid a window is the set of boundary faces whose centre lies inside it
    # (e.g. 6 x 0.1002 m = 0.601 m instead of 0.61 m); scale its speed so it delivers exactly
    # V_k * A_k, the model's exact inflow
    xc = [x0 + (i + 0.5) * h[0] for i in range(n[0])]
    flux_fix = []
    for (a, b, c, d) in WINDOWS:
        n_x = sum(1 for xi in xc if a <= xi <= b)
        flux_fix.append((b - a) / (n_x * h[0]))
    ubc = ["    walls   { type noSlip; }", "    columns { type noSlip; }"]
    for k in range(len(WINDOWS)):
        if V[k] > 0:
            ubc.append(f"""    window{k + 1}
    {{
        type            uniformFixedValue;
        uniformValue
        {{
            type table;
            values
            (
{ramp_table(V[k] * flux_fix[k], args.t_end)}
            );
        }}
    }}""")
        else:
            ubc.append(f"    window{k + 1} {{ type noSlip; }}")
    for j in range(len(DOORS)):
        # p = 0 with a free velocity, exactly like the model's door condition (backflow allowed;
        # inletOutlet would forbid it)
        ubc.append(f"    door{j + 1} {{ type pressureInletOutletVelocity; value uniform (0 0 0); }}")
    write(os.path.join(case, "0.orig/U"), "volVectorField", "U",
          "\ndimensions [0 1 -1 0 0 0 0];\ninternalField uniform (0 0 0);\nboundaryField\n{\n" + "\n".join(ubc) + "\n}\n")
    pbc = ["    walls   { type zeroGradient; }", "    columns { type zeroGradient; }"]
    pbc += [f"    window{k + 1} {{ type zeroGradient; }}" for k in range(len(WINDOWS))]
    pbc += [f"    door{j + 1} {{ type fixedValue; value uniform 0; }}" for j in range(len(DOORS))]
    write(os.path.join(case, "0.orig/p"), "volScalarField", "p",
          "\ndimensions [0 2 -2 0 0 0 0];\ninternalField uniform 0;\nboundaryField\n{\n" + "\n".join(pbc) + "\n}\n")

    # ---------------- constant/
    write(os.path.join(case, "constant/transportProperties"), "dictionary", "transportProperties",
          f"\ntransportModel  Newtonian;\nnu              {NU};\n")
    write(os.path.join(case, "constant/turbulenceProperties"), "dictionary", "turbulenceProperties",
          "\nsimulationType  laminar;\n")

    # ---------------- system/controlDict, fvSchemes, fvSolution, decomposeParDict
    write(os.path.join(case, "system/controlDict"), "dictionary", "controlDict", f"""
application     pimpleFoam;
startFrom       startTime;
startTime       0;
stopAt          endTime;
endTime         {args.t_end};
deltaT          0.001;
adjustTimeStep  yes;
maxCo           1.0;
maxDeltaT       0.05;
writeControl    adjustableRunTime;
writeInterval   {args.write_interval};
purgeWrite      0;
writeFormat     ascii;
writePrecision  8;
writeCompression on;       // gzip: ~3-4x smaller (the server disk filled up with ascii output)
timeFormat      general;
timePrecision   6;
runTimeModifiable true;
""")
    write(os.path.join(case, "system/fvSchemes"), "dictionary", "fvSchemes", """
ddtSchemes      { default backward; }
gradSchemes     { default Gauss linear; }
divSchemes
{
    default         none;
    div(phi,U)      Gauss linearUpwind grad(U);
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}
laplacianSchemes { default Gauss linear corrected; }
interpolationSchemes { default linear; }
snGradSchemes   { default corrected; }
""")
    write(os.path.join(case, "system/fvSolution"), "dictionary", "fvSolution", """
solvers
{
    p      { solver GAMG; smoother GaussSeidel; tolerance 1e-7; relTol 0.01; }
    pFinal { $p; relTol 0; }
    "(U|UFinal)" { solver smoothSolver; smoother symGaussSeidel; tolerance 1e-8; relTol 0; }
}
PIMPLE
{
    nOuterCorrectors 1;
    nCorrectors      2;
    nNonOrthogonalCorrectors 0;
    pRefCell 0;
    pRefValue 0;
}
""")
    write(os.path.join(case, "system/decomposeParDict"), "dictionary", "decomposeParDict",
          f"\nnumberOfSubdomains {args.procs};\nmethod scotch;\n")
    with open(os.path.join(case, "scenario.txt"), "w") as f:
        f.write(f"name {name}\nV {' '.join(f'{v:g}' for v in V)}\ndx {args.dx}\nn {n[0]} {n[1]} {n[2]}\n"
                f"nu {NU}\nt_end {args.t_end}\n")
    # consistency with the training code
    try:
        import re
        src = open(os.path.join(os.path.dirname(HERE), "train_gnot.py")).read()
        nu_train = float(re.search(r"^NU = ([0-9.eE+-]+)", src, re.M).group(1))
        assert abs(nu_train - NU) < 1e-12, f"train_gnot.NU = {nu_train} != {NU}"
    except (OSError, AttributeError):
        print("WARNING: could not check NU against train_gnot.py")
    print(f"case written: {case}\n  scenario {name}: V = {V}\n  grid {n[0]} x {n[1]} x {n[2]} "
          f"= {n[0] * n[1] * n[2]:,} cells before removing the columns")


if __name__ == "__main__":
    main()
