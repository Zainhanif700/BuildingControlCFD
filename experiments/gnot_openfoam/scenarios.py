"""
Phase-2 scenario list: 3 window zones by geometry, speeds 0 (closed) or 0.2-2.0 m/s per zone.

Zones (point_sampler.WINDOWS; split at the two large gaps of 2.09 m between W3|W4 and W6|W7):
  Z1 = W1-W3 (x 2.09-5.40 m), Z2 = W4-W6 (x 7.49-10.80 m), Z3 = W7-W8 (x 12.89-15.52 m).
All windows of a zone get the zone's speed (like the paper's vent groups).

Design (40 cases, deterministic, seed 0):
  S00             all closed (no flow; CO2 only -> no OpenFOAM run)          train
  S01-S09         one zone open at 0.5 / 1.0 / 2.0 m/s                        train
  S10-S12         all zones at 0.5 / 1.0 / 2.0 m/s                           train
  S13-S39         random: each zone closed with p = 0.3, else U(0.2, 2.0) m/s (0.05 steps),
                  no all-closed, no duplicates; 8 of them held out as TEST cases (never trained on)
Writes scenarios.txt: "<name> <train|test> <V1,...,V8> <z1 z2 z3>".
"""
import os

import numpy as np

import common  # noqa: F401
from point_sampler import WINDOWS

HERE = os.path.dirname(os.path.abspath(__file__))
ZONES = [(0, 1, 2), (3, 4, 5), (6, 7)]
V_LO, V_HI, P_CLOSED = 0.2, 2.0, 0.3
N_RANDOM, N_TEST, SEED = 27, 8, 0


def zone_to_V(z):
    V = [0.0] * len(WINDOWS)
    for zs, idx in zip(z, ZONES):
        for k in idx:
            V[k] = float(zs)
    return V


def build():
    # geometry check of the zoning: the two largest gaps between neighbouring windows separate the zones
    gaps = [WINDOWS[k + 1][0] - WINDOWS[k][1] for k in range(len(WINDOWS) - 1)]
    big = sorted(range(len(gaps)), key=lambda k: -gaps[k])[:2]
    assert sorted(big) == [2, 5], f"zones do not match the window gaps {gaps}"
    rows = [("S00", "train", (0.0, 0.0, 0.0))]
    for s in (0.5, 1.0, 2.0):
        for zi in range(3):
            z = [0.0, 0.0, 0.0]
            z[zi] = s
            rows.append((f"S{len(rows):02d}", "train", tuple(z)))
    for s in (0.5, 1.0, 2.0):
        rows.append((f"S{len(rows):02d}", "train", (s, s, s)))
    rng = np.random.default_rng(SEED)
    seen = {r[2] for r in rows}
    rand = []
    while len(rand) < N_RANDOM:
        z = tuple(0.0 if rng.random() < P_CLOSED else round(float(rng.uniform(V_LO, V_HI)) / 0.05) * 0.05
                  for _ in range(3))
        z = tuple(round(v, 2) for v in z)
        if max(z) == 0 or z in seen:
            continue
        seen.add(z)
        rand.append(z)
    test = set(rng.choice(N_RANDOM, N_TEST, replace=False).tolist())
    for i, z in enumerate(rand):
        rows.append((f"S{len(rows):02d}", "test" if i in test else "train", z))
    return rows


def main():
    rows = build()
    path = os.path.join(HERE, "scenarios.txt")
    with open(path, "w") as f:
        f.write("# name split V1..V8 zone_speeds(Z1=W1-W3 Z2=W4-W6 Z3=W7-W8) -- generated by scenarios.py\n")
        for name, split, z in rows:
            V = zone_to_V(z)
            f.write(f"{name} {split} {','.join(f'{v:g}' for v in V)} {' '.join(f'{v:g}' for v in z)}\n")
    n_test = sum(r[1] == "test" for r in rows)
    print(f"wrote {path}: {len(rows)} scenarios ({len(rows) - n_test} train, {n_test} test)")
    for name, split, z in rows:
        print(f"  {name} {split:5s} zones {z}")


if __name__ == "__main__":
    main()
